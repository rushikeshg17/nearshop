// Generates src/lib/icon-map.ts: a static import of every Lucide icon the seed catalogue uses,
// so product tiles render instantly instead of lazy-loading icons.
// Run: node scripts/gen-icon-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const data = join(here, "../../backend/database/seed/data");
const names = new Set(["Package"]);
for (const file of ["categories.json", "catalog.json"]) {
  for (const row of JSON.parse(readFileSync(join(data, file), "utf8"))) if (row.icon) names.add(row.icon);
}
const sorted = [...names].sort();
const out = `// Generated by scripts/gen-icon-map.mjs from the seed catalogue. Do not edit by hand.
import type { LucideIcon } from "lucide-react";
import {
${sorted.map((n) => `  ${n},`).join("\n")}
} from "lucide-react";

export const ICONS: Record<string, LucideIcon> = {
${sorted.map((n) => `  ${n},`).join("\n")}
};
`;
writeFileSync(join(here, "../src/lib/icon-map.ts"), out);
console.log(`icon-map.ts: ${sorted.length} icons`);
